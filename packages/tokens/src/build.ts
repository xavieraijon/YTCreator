import { mkdirSync, writeFileSync } from 'node:fs'
import { createContrastPairs } from './contrast-pairs.ts'
import { tokens as allTokens } from './index.ts'
import {
  isTextOrIcon,
  isThemed,
  refFor,
  type ContrastPair,
  type Level,
  type Ref,
  type Theme,
  type ThemedRef,
  type Token,
} from './types.ts'

const prefix: Readonly<Record<Level, string>> = { primitive: 'p', semantic: 's', component: 'c' }

const property = (ref: Ref<Level>) => `--${prefix[ref.level]}-${ref.name}`

const cssValue = (value: ThemedRef<Level>) =>
  isThemed(value)
    ? `light-dark(var(${property(value.light)}), var(${property(value.dark)}))`
    : `var(${property(value)})`

/** Breakpoints cannot be read inside `@media`, so they are exported as constants instead (research R5). */
const isEmitted = (token: Token) => token.category !== 'breakpoint'

/** Authoring rules of contracts/tokens.md. Returns every problem found. */
export function validate(tokens: readonly Token[]): string[] {
  const semanticNames = new Set(tokens.filter((token) => token.level === 'semantic').map((token) => token.name))
  return tokens.flatMap((token) => {
    if (token.level !== 'semantic') return []
    if (isTextOrIcon(token) && !token.allowedOn) return [`${token.name}: text and icon tokens must declare allowedOn`]
    return (token.allowedOn ?? [])
      .filter((background) => !semanticNames.has(background))
      .map((background) => `${token.name}: allowedOn names an unknown semantic token (${background})`)
  })
}

export function renderCss(tokens: readonly Token[]): string {
  const emitted = tokens.filter(isEmitted)
  const declaration = (token: Token) =>
    `    ${property(token)}: ${token.level === 'primitive' ? token.value : cssValue(token.value)};`
  const level = (name: Level) => emitted.filter((token) => token.level === name).map(declaration)
  const overrides = (pick: (token: Token) => ThemedRef<'primitive'> | undefined) =>
    emitted.flatMap((token) => {
      const value = pick(token)
      return value ? [`      ${property(token)}: ${cssValue(value)};`] : []
    })

  const reducedMotion = overrides((token) => (token.level === 'semantic' ? token.reducedMotion : undefined))
  const reducedTransparency = overrides((token) => (token.level === 'semantic' ? token.reducedTransparency : undefined))
  const block = (condition: string, lines: string[]) =>
    lines.length ? [``, `  ${condition} {`, `    :root {`, ...lines, `    }`, `  }`] : []

  return [
    `/* Generated by packages/tokens/src/build.ts. Do not edit. */`,
    `@layer tokens {`,
    `  :root { color-scheme: light dark; }`,
    `  :root[data-theme='light'] { color-scheme: light; }`,
    `  :root[data-theme='dark'] { color-scheme: dark; }`,
    ``,
    `  :root {`,
    ...level('primitive'),
    ``,
    ...level('semantic'),
    ...(level('component').length ? [``, ...level('component')] : []),
    `  }`,
    ...block('@media (prefers-reduced-motion: reduce)', reducedMotion),
    ...block('@media (prefers-reduced-transparency: reduce)', reducedTransparency),
    ...block('@supports not (backdrop-filter: blur(1px))', reducedTransparency),
    `}`,
    ``,
  ].join('\n')
}

export interface TokenEntry {
  readonly name: string
  readonly cssProperty: string
  readonly level: Level
  readonly category: Token['category']
  readonly description?: string
  /** Literal value after resolving every reference. */
  readonly value: Readonly<Record<Theme, string>>
  /** Token it points to in each theme; `null` for primitives. */
  readonly ref: Readonly<Record<Theme, string>> | null
  readonly allowedOn?: readonly string[]
}

export interface TokensJson {
  readonly tokens: readonly TokenEntry[]
  readonly contrastPairs: readonly ContrastPair[]
}

export function createTokensJson(tokens: readonly Token[], contrastPairs: readonly ContrastPair[]): TokensJson {
  const byName = new Map(tokens.map((token) => [token.name, token]))
  const resolve = (token: Token, theme: Theme): string => {
    if (token.level === 'primitive') return token.value
    const next = byName.get(refFor<Level>(token.value, theme).name)
    if (!next) throw new Error(`${token.name} points to an unknown token`)
    return resolve(next, theme)
  }

  return {
    tokens: tokens.map((token) => ({
      name: token.name,
      cssProperty: property(token),
      level: token.level,
      category: token.category,
      description: token.description,
      value: { light: resolve(token, 'light'), dark: resolve(token, 'dark') },
      ref:
        token.level === 'primitive'
          ? null
          : { light: refFor<Level>(token.value, 'light').name, dark: refFor<Level>(token.value, 'dark').name },
      ...(token.level === 'semantic' && token.allowedOn ? { allowedOn: token.allowedOn } : {}),
    })),
    contrastPairs,
  }
}

export function renderBreakpoints(tokens: readonly Token[]): string {
  const entries = tokens
    .filter((token) => token.level === 'primitive' && token.category === 'breakpoint')
    .map((token) => `${token.name.replace(/^breakpoint-/, '')}: '${token.level === 'primitive' ? token.value : ''}'`)
  return [
    `// Generated by packages/tokens/src/build.ts. Do not edit.`,
    `export const breakpoints = { ${entries.join(', ')} } as const`,
    ``,
  ].join('\n')
}

if (import.meta.main) {
  const problems = validate(allTokens)
  if (problems.length) {
    console.error(`Token build failed:\n${problems.map((problem) => `  - ${problem}`).join('\n')}`)
    process.exit(1)
  }
  const dist = new URL('../dist/', import.meta.url)
  mkdirSync(dist, { recursive: true })
  writeFileSync(new URL('tokens.css', dist), renderCss(allTokens))
  const json = createTokensJson(allTokens, createContrastPairs(allTokens))
  writeFileSync(new URL('tokens.json', dist), `${JSON.stringify(json, null, 2)}\n`)
  writeFileSync(new URL('breakpoints.ts', dist), renderBreakpoints(allTokens))
  console.log(`Tokens built: ${allTokens.length} tokens, ${json.contrastPairs.length} contrast pairs.`)
}
